package com.se.frms.decision.service;

import com.se.frms.decision.entity.Decision;
import com.se.frms.decision.repository.DecisionRepository;
import jakarta.annotation.PreDestroy;
import java.time.LocalDateTime;
import java.util.UUID;
import java.util.concurrent.Executors;
import java.util.concurrent.ScheduledExecutorService;
import java.util.concurrent.TimeUnit;
import lombok.extern.slf4j.Slf4j;
import org.slf4j.MDC;
import org.springframework.scheduling.annotation.Async;
import org.springframework.stereotype.Service;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

/**
 * Saves the decision row after the decision response has been returned (@Async,
 * unchanged). One row per transaction: an existing row (re-evaluation) is updated,
 * otherwise a new row is inserted - exactly as before.
 *
 * Changes (same rows, same ids as before):
 *  - The new row's id is generated by Hibernate (Decision.id is @GeneratedValue).
 *    Before, the code also set an id that Hibernate then ignored - it only caused an
 *    extra SELECT (merge) before every INSERT and the row still got a generated id.
 *  - Retry: before, a failed save (e.g. no free DB connection in a burst) was only
 *    logged and the decision row was lost. Now a failed attempt is retried after
 *    1 s, 2 s and 5 s (4 attempts, ~8 s in total). Each attempt repeats the same
 *    "find by transaction id, then update or insert" in its own transaction, so a
 *    retry can never create a second row (transaction_id is unique) and keeps the
 *    original createdAt / updatedAt passed in by the caller. Retries wait on their
 *    own small scheduler, never on the @Async pool. If the service stops while a
 *    retry is waiting, that save is lost (as before).
 */
@Service
@Slf4j
public class DecisionPersistenceService {

    private static final String SYSTEM_USER = "DECISION_SERVICE";
    private static final String MDC_KEY = "requestId";
    // Delay before attempt 2, 3 and 4.
    private static final long[] RETRY_DELAYS_MS = {1_000L, 2_000L, 5_000L};

    private final DecisionRepository decisionRepository;
    private final TransactionTemplate transactionTemplate;
    private final ScheduledExecutorService retryScheduler = Executors.newScheduledThreadPool(2, runnable -> {
        Thread thread = new Thread(runnable, "decision-persist-retry");
        thread.setDaemon(true);
        return thread;
    });

    public DecisionPersistenceService(DecisionRepository decisionRepository,
                                      PlatformTransactionManager transactionManager) {
        this.decisionRepository = decisionRepository;
        this.transactionTemplate = new TransactionTemplate(transactionManager);
    }

    @Async
    public void saveDecision(
            UUID decisionId,
            UUID transactionId,
            UUID scoringId,
            Integer totalRiskScore,
            String finalDecision,
            String reason,
            LocalDateTime createdAt,
            LocalDateTime updatedAt
    ) {
        DecisionData data = new DecisionData(decisionId, transactionId, scoringId, totalRiskScore,
                finalDecision, reason, createdAt, updatedAt);
        attempt(1, data, System.nanoTime());
    }

    private record DecisionData(UUID decisionId, UUID transactionId, UUID scoringId, Integer totalRiskScore,
                                String finalDecision, String reason, LocalDateTime createdAt,
                                LocalDateTime updatedAt) {
    }

    private void attempt(int attemptNo, DecisionData data, long startedAt) {
        try {
            UUID savedId = transactionTemplate.execute(status -> upsert(data));
            log.debug(
                    "Decision persisted asynchronously transactionId={}, decisionId={}, attempt={}, elapsedMs={}",
                    data.transactionId(),
                    savedId,
                    attemptNo,
                    elapsedMillis(startedAt)
            );
        } catch (RuntimeException ex) {
            if (attemptNo > RETRY_DELAYS_MS.length) {
                log.error(
                        "Async decision persistence failed after {} attempts transactionId={}, decisionId={}",
                        attemptNo,
                        data.transactionId(),
                        data.decisionId(),
                        ex
                );
                return;
            }
            long delayMs = RETRY_DELAYS_MS[attemptNo - 1];
            log.warn(
                    "Async decision persistence failed transactionId={}, decisionId={}, attempt={} - retrying in {} ms: {}",
                    data.transactionId(),
                    data.decisionId(),
                    attemptNo,
                    delayMs,
                    ex.getMessage()
            );
            String requestId = MDC.get(MDC_KEY);
            retryScheduler.schedule(() -> {
                if (requestId != null) {
                    MDC.put(MDC_KEY, requestId);
                }
                try {
                    attempt(attemptNo + 1, data, startedAt);
                } finally {
                    MDC.remove(MDC_KEY);
                }
            }, delayMs, TimeUnit.MILLISECONDS);
        }
    }

    /** Same update-or-insert as before; returns the id of the saved row. */
    private UUID upsert(DecisionData data) {
        Decision decision = decisionRepository.findByTransactionId(data.transactionId())
                .orElseGet(Decision::new);
        decision.setTransactionId(data.transactionId());
        decision.setScoringId(data.scoringId());
        decision.setTotalRiskScore(data.totalRiskScore());
        decision.setFinalDecision(data.finalDecision());
        decision.setDecisionReason(data.reason());
        decision.setStatus(true);
        decision.setCreatedBy(SYSTEM_USER);
        if (decision.getCreatedAt() == null) {
            decision.setCreatedAt(data.createdAt());
        }
        decision.setUpdatedAt(data.updatedAt());
        return decisionRepository.save(decision).getId();
    }

    @PreDestroy
    void shutdown() {
        retryScheduler.shutdownNow();
    }

    private long elapsedMillis(long startedAt) {
        return (System.nanoTime() - startedAt) / 1_000_000;
    }
}
